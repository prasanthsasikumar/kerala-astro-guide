// i0: 0-based nakshatra index (0 = Ashwini)
export function nakName(i0, db) {
  const l = lang();
  if (l === "ml") return db.tblMalayalamNakshatra[i0].Name;
  return NAK[l]?.[i0] ?? NAK_EN[i0];
}

// i0: 0-based sign index (0 = Mesha)
export function rasiName(i0) {
  const l = lang();
  if (l === "ml") return RASI_ML[i0];
  return RASI[l]?.[i0] ?? RASI_EN[i0];
}
